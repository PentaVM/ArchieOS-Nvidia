const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const api=vm.createContext({});
const source=path.join(__dirname,'../qml/ModelActivity.js');
if(fs.existsSync(source)) vm.runInContext(fs.readFileSync(source,'utf8').replace(/^\.pragma library\s*/m,''),api);
assert.equal(typeof api.fromSnapshot,'function','missing attributed model activity projection');
const now=100000;
const row=(id,at=90000)=>({model_id:id,state:'recent_completed',observed_at_ms:at,
  expires_at_ms:at+30000,output_tokens:120,request_elapsed_ms:2500,effective_output_tps_x1000:48000});
const snapshot=rows=>({source:'live',daemon_reachable:true,metrics:{model_inference:rows}});
const read=(s,t=now,connected=true)=>JSON.parse(JSON.stringify(api.fromSnapshot(s,t,connected)));
assert.equal(read(snapshot([row('a')]),now,false),null);
assert.equal(read({metrics:{gauges:{'inference.last.effective_output_tokens_per_second_x1000':99000}}}),null);
assert.deepEqual(read(snapshot([])),[]);
assert.deepEqual(read(snapshot([row('a')])),[{id:'a',label:'a',active:true,stale:false,state:'reciente',tps_available:true,tps:48}]);
assert.deepEqual(read(snapshot([row('expired',70000),row('future',101001)])),[]);
assert.equal(read(snapshot([row('a')]),120000).length,0);
assert.deepEqual(read({daemon_reachable:false,metrics:{model_inference:[row('a')]}}),null);
const missing=row('missing');missing.output_tokens=null;missing.effective_output_tps_x1000=null;
assert.equal(read(snapshot([missing]))[0].tps_available,false);
assert.equal(read(snapshot([Object.assign(row('bad'),{effective_output_tps_x1000:Infinity})]))[0].tps_available,false);
assert.deepEqual(read(snapshot([row('model with whitespace'),row('a'),row('a')])),read(snapshot([row('a')])));
assert.equal(read(snapshot(Array.from({length:10},(_,i)=>row('m'+i,90000+i)))).length,6);
assert.equal(read(snapshot([row('older',90000),row('newer',95000)]))[0].id,'newer');
assert.equal(read({...snapshot([row('replayed')]),source:'fixture'}),null);
assert.equal(read({...snapshot([row('unknown')]),source:undefined}),null);
assert.equal(read({...snapshot([row('unconfirmed')]),daemon_reachable:undefined}),null);
console.log('model activity: 15 projection contracts passed');
